from tensorflow.keras.datasets import cifar10
import cv2
import numpy as np

# Step 1: Load CIFAR-10 dataset
(_, _), (cifar_images, cifar_labels) = cifar10.load_data()

# Step 2: Preprocess CIFAR-10 images
# Convert to grayscale and resize to match your face dataset dimensions
cifar_preprocessed = []
for img in cifar_images:
    img_gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)  # Convert to grayscale
    img_resized = cv2.resize(img_gray, (160, 160))  # Resize to 160x160
    cifar_preprocessed.append(img_resized.flatten())  # Flatten the image

# Convert to NumPy array
cifar_preprocessed = np.array(cifar_preprocessed)
print(f"CIFAR-10 processed images shape: {cifar_preprocessed.shape}")

# Step 1: Assign labels
# Face images (label=1), CIFAR-10 (label=0)
face_labels = np.ones(flattened_images.shape[0])
cifar_labels = np.zeros(cifar_preprocessed.shape[0])

# Step 2: Combine datasets
combined_images = np.vstack((flattened_images, cifar_preprocessed))
combined_labels = np.hstack((face_labels, cifar_labels))

# Print combined dataset shape
print(f"Combined images shape: {combined_images.shape}")
print(f"Combined labels shape: {combined_labels.shape}")

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report

# Step 1: Split the data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(combined_images, combined_labels, test_size=0.3, random_state=42)

# Step 2: Train Logistic Regression
clf = LogisticRegression(random_state=42, max_iter=1000)
clf.fit(X_train, y_train)

# Step 3: Predict on the test set
y_pred = clf.predict(X_test)

from sklearn.metrics import classification_report

# Generate classification report
report = classification_report(y_test, y_pred, target_names=["Non-Face", "Face"])
print("Classification Report:")
print(report)


"""The below  code performs mean-centering, a crucial preprocessing step in many machine learning and data analysis tasks, including Principal Component Analysis (PCA). The goal of mean-centering is to shift the data so that its mean becomes zero. This ensures that subsequent analyses focus on the variations in the data rather than the absolute values.


"""

# Step 2: Mean-center the data
mean_centered_data = flattened_images - mean_face

# Verify the mean of the mean-centered data (should be close to zero)
mean_of_centered_data = np.mean(mean_centered_data)
print(f"Mean of mean-centered data: {mean_of_centered_data:.5f}")

mean_of_centered_data = np.mean(mean_centered_data)
print(f"Exact mean of mean-centered data: {mean_of_centered_data:.15f}")

# Step 3: Compute the smaller covariance matrix (N x N)
N = mean_centered_data.shape[0]  # Number of images
small_cov_matrix = np.dot(mean_centered_data, mean_centered_data.T) / N  # Smaller covariance matrix

# Step 4: Perform eigenvalue decomposition on the smaller covariance matrix
small_eigenvalues, small_eigenvectors = np.linalg.eigh(small_cov_matrix)

# Step 5: Map eigenvectors back to the original space
eigenvectors = np.dot(mean_centered_data.T, small_eigenvectors)  # Map to original space
eigenvectors = eigenvectors / np.linalg.norm(eigenvectors, axis=0)  # Normalize

# Step 6: Sort eigenvalues and eigenvectors
sorted_indices = np.argsort(-small_eigenvalues)  # Sort eigenvalues in descending order
eigenvalues = small_eigenvalues[sorted_indices]
eigenvectors = eigenvectors[:, sorted_indices]

